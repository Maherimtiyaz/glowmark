#!/usr/bin/env python3
"""Build the landing page's real demo pages.

The site used to ship a second, JavaScript Markdown renderer for its "live
demo".  That made the demo look right while the Python CLI could produce
different HTML.  Now the demo is generated by the same engine the CLI uses,
and ``--check`` fails CI when the committed output drifts from the source.
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from glowmark.render import (  # noqa: E402
    codehilite_css,
    load_assets,
    render_page,
    render_text,
)

SITE = ROOT / "site"
DOCS = ROOT / "docs"
INDEX = DOCS / "index.html"

GENERATED = "<!-- generated by scripts/build_site.py; do not edit -->\n"


def _page(source: Path, default_title: str) -> str:
    text = source.read_text(encoding="utf-8")
    doc = render_text(text, default_title=default_title)
    css, js = load_assets()
    page = render_page(
        doc,
        css=css,
        js=js,
        code_css=codehilite_css(),
        theme="auto",
    )
    return GENERATED + page


def _raw_block(source: Path) -> str:
    text = source.read_text(encoding="utf-8").rstrip("\n")
    return '<pre class="raw">' + html.escape(text) + "</pre>"


def _replace_region(text: str, start: str, end: str, body: str) -> str:
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f"build_site: markers not found: {start} / {end}")
    return pattern.sub(lambda _match: f"{start}\n{body}\n{end}", text, count=1)


def build(check: bool = False) -> int:
    demo_page = _page(SITE / "demo.md", "glowmark demo")
    compare_page = _page(SITE / "compare.md", "glowmark comparison")

    index = INDEX.read_text(encoding="utf-8")
    index = _replace_region(
        index,
        "<!--GLOWMARK:DEMO_SOURCE:START-->",
        "<!--GLOWMARK:DEMO_SOURCE:END-->",
        _raw_block(SITE / "demo.md"),
    )
    index = _replace_region(
        index,
        "<!--GLOWMARK:COMPARE_SOURCE:START-->",
        "<!--GLOWMARK:COMPARE_SOURCE:END-->",
        _raw_block(SITE / "compare.md"),
    )

    outputs = {
        DOCS / "demo.html": demo_page,
        DOCS / "compare.html": compare_page,
        INDEX: index,
    }

    if check:
        stale = [
            path
            for path, content in outputs.items()
            if not path.exists() or path.read_bytes() != content.encode("utf-8")
        ]
        if stale:
            names = ", ".join(str(path.relative_to(ROOT)) for path in stale)
            print(f"build_site: out of date: {names}", file=sys.stderr)
            print("build_site: run `python scripts/build_site.py`", file=sys.stderr)
            return 1
        print("build_site: site is up to date")
        return 0

    for path, content in outputs.items():
        path.write_bytes(content.encode("utf-8"))
    print("build_site: wrote " + ", ".join(str(path.relative_to(ROOT)) for path in outputs))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify generated files are up to date instead of writing them",
    )
    args = parser.parse_args()
    return build(check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
